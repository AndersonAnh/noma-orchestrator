package ru.vtb.msa.noma.orchestrator.integration.risk.pojo;

import lombok.Builder;

import java.math.BigDecimal;
import java.util.UUID;

/**
 * Запрос для оценки риска страхового полиса.
 * <p>
 * Содержит полный набор параметров, необходимых для риск-сервиса для комплексного анализа
 * и расчета коэффициента риска. Используется при создании страховых предложений.
 * </p>
 *
 * @param clientId              уникальный идентификатор клиента (UUID). Используется для отслеживания
 *                              истории клиента, выявления паттернов поведения и проверки предыдущих полисов.
 *                              Позволяет риск-сервису применить персонализированный коэффициент риска.
 * @param age                   возраст застрахованного лица в годах. Ключевой фактор для оценки риска.
 *                              Влияет на вероятность наступления страхового события.
 *                              Диапазон: 18-100 лет.
 * @param hasDangerousHobbies   флаг наличия опасных хобби (экстремальные виды спорта, альпинизм и т.д.).
 *                              Значительно повышает коэффициент риска.
 *                              Если true, риск-сервис применит повышающий коэффициент.
 * @param isHighRiskOccupation  флаг высокорисковой профессии (шахтер, строитель, летчик и т.д.).
 *                              Профессиональные риски влияют на оценку.
 *                              Если true, риск-сервис применит повышающий коэффициент.
 * @param desiredCoverageAmount желаемая сумма страхового покрытия в рублях.
 *                              Большие суммы требуют более тщательной проверки.
 *                              Риск-сервис может установить пороги для дополнительной верификации.
 *                              Пример: полисы свыше 10 млн требуют усиленной проверки.
 * @param policyTermYears       срок действия полиса в годах.
 *                              Влияет на профиль риска:
 *                              - Краткосрочные (1-2 года): повышенный риск мошенничества
 *                              - Среднесрочные (5-15 лет): стандартный риск
 *                              - Долгосрочные (20-30 лет): более стабильный риск
 * @param coverageType          тип страхового покрытия (TERM, WHOLE_LIFE, INVESTMENT).
 *                              Каждый тип имеет свой базовый коэффициент риска:
 *                              - TERM (срочное): 1.3 (повышенный риск)
 *                              - WHOLE_LIFE (пожизненное): 1.0 (стандартный)
 *                              - INVESTMENT (инвестиционное): 1.5 (требует дополнительного анализа)
 * @param beneficiaryRelation   отношение бенефициара к застрахованному лицу.
 *                              Используется для выявления потенциального мошенничества.
 *                              Примеры: "Супруга", "Ребенок", "Компания XYZ", "Незнакомец".
 *                              Влияет на коэффициент риска:
 *                              - Близкие родственники: 0.8-0.9 (низкий риск)
 *                              - Компании/организации: 2.0+ (высокий риск)
 * @author Orchestrator Team
 * @version 1.0
 * @see ru.vtb.msa.noma.orchestrator.integration.risk.client.RiskClient
 * @see ru.vtb.msa.noma.orchestrator.integration.risk.builder.RiskRequestBuilder
 */
@Builder
public record RiskRequest(
        UUID clientId,
        Integer age,
        Boolean hasDangerousHobbies,
        Boolean isHighRiskOccupation,
        BigDecimal desiredCoverageAmount,
        Integer policyTermYears,
        String coverageType,
        String beneficiaryRelation
) {
}
